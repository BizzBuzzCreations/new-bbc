// Generates lib/bizzbee/legalKnowledge.js — plain-text sections of the four
// legal pages (privacy policy, cookie policy, disclaimer, terms & conditions)
// so BizzBee can answer questions about them without reading JSX at runtime.
//
// Re-run after editing any of those pages:  node scripts/gen-legal-knowledge.cjs
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const PAGES = [
  { dir: "privacy-policy", title: "Privacy Policy", url: "/privacy-policy" },
  { dir: "cookie-policy", title: "Cookie Policy", url: "/cookie-policy" },
  { dir: "disclaimer", title: "Disclaimer", url: "/disclaimer" },
  { dir: "terms-and-conditions", title: "Terms & Conditions", url: "/terms-and-conditions" },
];

const ENTITIES = { "&amp;": "&", "&apos;": "'", "&quot;": '"', "&ldquo;": '"', "&rdquo;": '"', "&lsquo;": "'", "&rsquo;": "'", "&nbsp;": " ", "&mdash;": "-", "&ndash;": "-" };
const decode = (s) =>
  s
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&[a-z]+;/gi, (e) => ENTITIES[e.toLowerCase()] ?? " ");

function textOf(jsx) {
  return decode(
    jsx
      .replace(/\{\/\*[\s\S]*?\*\/\}/g, " ")
      .replace(/<li[^>]*>/g, " • ")
      .replace(/<\/?>/g, " ")
      .replace(/<br\s*\/?>/g, " ")
      .replace(/<[^>]+>/g, " ")
      .replace(/\{"([^"]*)"\}/g, "$1")
      .replace(/\{[^}]*\}/g, " ")
      .replace(/[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/gu, "")
      .replace(/\[Important:[^\]]*\]/gi, " ") // internal drafting note, never shown to visitors
      .replace(/\)\s*;?\s*\}?\s*$/, " ") // trailing JSX leftovers
      .replace(/\s+/g, " ")
      .trim(),
  );
}

const out = [];
for (const p of PAGES) {
  const file = path.join(ROOT, "app", "(main)", p.dir, "page.js");
  const src = fs.readFileSync(file, "utf8");
  const body = src.split("return (")[1] || "";
  const parts = body.split(/<h2[^>]*>/);
  const intro = textOf(parts[0].replace(/<h1[\s\S]*?<\/h1>/, " "));
  if (intro) out.push({ page: p.title, url: p.url, heading: "Overview", text: intro });
  for (const part of parts.slice(1)) {
    const [h, ...rest] = part.split(/<\/h2>/);
    const heading = textOf(h);
    const text = textOf(rest.join(" "));
    if (heading && text) out.push({ page: p.title, url: p.url, heading, text });
  }
}

const header =
  "// GENERATED by scripts/gen-legal-knowledge.cjs — do not edit by hand.\n" +
  "// Sections of the privacy policy, cookie policy, disclaimer and terms & conditions.\n";
fs.writeFileSync(path.join(ROOT, "lib", "bizzbee", "legalKnowledge.js"), `${header}export const LEGAL_SECTIONS = ${JSON.stringify(out, null, 2)};\n`);
console.log(`wrote ${out.length} sections`);
